/**
 * Generates a compact 1°-resolution land/water bitmask of the world from the
 * Natural Earth 110m land polygons shipped with `world-atlas`.
 *
 * The mask drives both the dotted 3D globe in the hero and the footer's
 * dot-matrix world map, so the site ships no GeoJSON at runtime.
 *
 * Usage: npm run generate:worldmap
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { feature } from 'topojson-client'
import { geoContains } from 'd3-geo'

const require = createRequire(import.meta.url)
const topology = JSON.parse(readFileSync(require.resolve('world-atlas/land-110m.json'), 'utf8'))
const land = feature(topology, topology.objects.land)

const COLS = 360
const ROWS = 180
const rows = []

for (let r = 0; r < ROWS; r++) {
  const lat = 90 - (r + 0.5)
  let bits = ''
  for (let c = 0; c < COLS; c++) {
    const lon = -180 + (c + 0.5)
    bits += geoContains(land, [lon, lat]) ? '1' : '0'
  }
  let hex = ''
  for (let i = 0; i < bits.length; i += 4) hex += parseInt(bits.slice(i, i + 4), 2).toString(16)
  rows.push(hex)
}

const out = `// AUTO-GENERATED by scripts/generate-world-mask.mjs — do not edit by hand.
// 1° equirectangular land mask (${COLS}×${ROWS}); row 0 is 90°N, column 0 is 180°W.
// Each row is ${COLS / 4} hex chars (4 cells per char, MSB first).
// Source: Natural Earth 110m land via world-atlas (public domain).

export const WORLD_MASK_COLS = ${COLS}
export const WORLD_MASK_ROWS = ${ROWS}

export const WORLD_MASK: readonly string[] = [
${rows.map((r) => `  '${r}',`).join('\n')}
]
`
writeFileSync(new URL('../src/data/worldMask.ts', import.meta.url), out)
console.log(`Wrote src/data/worldMask.ts (${COLS}x${ROWS})`)
